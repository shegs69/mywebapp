@app.get("/health")
def health():
    with db_cursor() as cur:
        cur.execute("SELECT 1")
    return jsonify(status="ok")


@app.get("/orders")
def list_orders():
    user_id = request.args.get("user_id", type=int)
    with db_cursor() as cur:
        if user_id is None:
            orders = fetch_orders(cur)
        else:
            orders = fetch_orders(cur, "o.user_id = %s", (user_id,))
    return jsonify(orders)


@app.get("/orders/<int:order_id>")
def get_order(order_id):
    with db_cursor() as cur:
        orders = fetch_orders(cur, "o.id = %s", (order_id,))
    if not orders:
        abort(404, description="Order not found")
    return jsonify(orders[0])


@app.post("/orders")
def create_order():
    user_id, quantities = parse_order(read_json_object())

    if fetch_json(f"{USERS_API}/users/{user_id}", "Users") is None:
        abort(422, description=f"User {user_id} does not exist")

    ids_str = ",".join(str(pid) for pid in quantities.keys())
    products = fetch_json(f"{PRODUCTS_API}/products?ids={ids_str}", "Products") or []
    product_map = {p["id"]: p for p in products}

    lines = []
    total = Decimal("0.00")
    for product_id, quantity in sorted(quantities.items()):
        product = product_map.get(product_id)
        if product is None:
            abort(422, description=f"Product {product_id} does not exist")
        unit_price = Decimal(str(product["price"])).quantize(Decimal("0.01"))
        total += unit_price * quantity
        lines.append((product_id, product["name"], unit_price, quantity))

    with db_cursor() as cur:
        cur.execute(
            "INSERT INTO orders (user_id, total) VALUES (%s, %s) RETURNING id",
            (user_id, total),
        )
        order_id = cur.fetchone()["id"]
        cur.executemany(
            "INSERT INTO order_items (order_id, product_id, product_name, unit_price, quantity) "
            "VALUES (%s, %s, %s, %s, %s)",
            [(order_id, *line) for line in lines],
        )
        order = fetch_orders(cur, "o.id = %s", (order_id,))[0]

    body = {"message": "Order created", "order_id": order_id, "order": order}
    return jsonify(body), 201, {"Location": url_for("get_order", order_id=order_id)}


